import assert from 'node:assert/strict';
import {parseLogicalRows,stableIncremental,selectionAudit} from './background_merchant_collector.mjs';
const h=['商家ID','商家名称','推荐时间','状态'];
const valid=['12345678','甲','2026-09-15 10:00:00','待处理'];
assert.throws(()=>parseLogicalRows(h,[valid,['bad']]),/column-mismatch:1/);
assert.throws(()=>parseLogicalRows(h,[valid,['invalid','乙','2026-09-16 10:00:00','待处理']]),/id-invalid:1/);
assert.throws(()=>parseLogicalRows(['商家ID','商家ID'],[['12345678','87654321']]),/headers-duplicate/);
const rows=[{merchantId:'1',recommendTime:'2026-09-15 10:00:00',status:'待处理'},{merchantId:'2',recommendTime:'2026-09-16 10:00:00',status:'完成'},{merchantId:'3',recommendTime:'2026-09-16 10:00:00',status:'待处理'}];
const cursor=rows[0];
assert.throws(()=>stableIncremental(rows,cursor,'2026-09-16'),/cursor-outside-filter-range/);
assert.throws(()=>stableIncremental(rows,{...cursor,merchantId:'missing'},'2026-09-15'),/cursor-not-unique/);
assert.throws(()=>stableIncremental([cursor,...rows],cursor,'2026-09-15'),/cursor-not-unique/);
const audit=selectionAudit(rows,cursor,'2026-09-15');
assert.deepEqual([audit.totalRows,audit.pendingRows,audit.excludedAtOrBeforeCursor,audit.excludedAfterCursorNotPending,audit.targetCount],[3,2,1,1,1]);
assert.equal(audit.totalRows,audit.excludedAtOrBeforeCursor+audit.excludedAfterCursorNotPending+audit.targetCount);
assert.deepEqual(stableIncremental(rows,rows[1],'2026-09-15').map(x=>x.merchantId),['3']);
assert.equal(selectionAudit(rows,rows[2],'2026-09-15').targetCount,0);
assert.equal(parseLogicalRows(h,[valid]).length,1);
console.log(JSON.stringify({ok:true,assertions:11}));
